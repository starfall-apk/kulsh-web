window.t = function (key, lang) {
  const L = lang || (window.AppState && window.AppState.settings.lang) || 'ru';
  return (window.I18N[L] && window.I18N[L][key]) || (window.I18N.ru[key]) || key;
};

window.applyI18n = function (lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = window.t(key, lang);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', window.t(key, lang));
  });
};
